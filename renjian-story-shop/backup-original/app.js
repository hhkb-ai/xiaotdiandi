function levenshteinDistance(a, b, maxDistance = 3) {
  if (a === b) return 0;
  if (!a || !b) return Math.max(a.length, b.length);
  if (Math.abs(a.length - b.length) > maxDistance) return maxDistance + 1;

  let previous = Array.from({ length: b.length + 1 }, (_, index) => index);
  for (let i = 1; i <= a.length; i += 1) {
    const current = [i];
    let rowMin = current[0];
    for (let j = 1; j <= b.length; j += 1) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      const value = Math.min(
        previous[j] + 1,
        current[j - 1] + 1,
        previous[j - 1] + cost
      );
      current[j] = value;
      rowMin = Math.min(rowMin, value);
    }
    if (rowMin > maxDistance) return maxDistance + 1;
    previous = current;
  }
  return previous[b.length];
}

function isSubsequence(query, text) {
  if (!query || !text || query.length > text.length) return false;
  let cursor = 0;
  for (const char of text) {
    if (char === query[cursor]) cursor += 1;
    if (cursor === query.length) return true;
  }
  return false;
}

function hasApproximateSubstring(query, text, options = {}) {
  if (!query || !text) return false;
  const { maxTextLength = 700 } = options;
  const compactQuery = compactSearchText(query);
  const compactText = compactSearchText(text);
  if (compactQuery.length < 3 || compactText.length < 2 || compactText.length > maxTextLength) return false;
  const maxDistance = compactQuery.length <= 4 ? 1 : compactQuery.length <= 8 ? 2 : 3;
  const minLength = Math.max(2, compactQuery.length - maxDistance);
  const maxLength = compactQuery.length + maxDistance;
  const hasCjk = /[\u4e00-\u9fa5]/.test(compactQuery);
  const distinctiveChars = hasCjk ? getDistinctiveSearchChars(compactQuery) : [];
  if (!hasSharedSearchBigram(compactQuery, compactText)) return false;
  if (hasCjk && distinctiveChars.length) {
    const minOverlap = Math.max(1, distinctiveChars.length - maxDistance);
    if (getCharOverlap(distinctiveChars, compactText) < minOverlap) return false;
  }

  for (let length = minLength; length <= maxLength; length += 1) {
    if (length > compactText.length) continue;
    for (let index = 0; index <= compactText.length - length; index += 1) {
      const fragment = compactText.slice(index, index + length);
      if (hasCjk && distinctiveChars.length) {
        const minOverlap = Math.max(1, distinctiveChars.length - maxDistance);
        if (getCharOverlap(distinctiveChars, fragment) < minOverlap) continue;
      }
      if (levenshteinDistance(compactQuery, fragment, maxDistance) <= maxDistance) return true;
    }
  }
  return false;
}

function getFuzzyTextScore(query, text, options = {}) {
  const { approximate = true } = options;
  const normalizedQuery = normalizeSearchText(query);
  const normalizedText = normalizeSearchText(text);
  const compactQuery = compactSearchText(query);
  const compactText = compactSearchText(text);
  if (!compactQuery) return 0;

  let score = 0;
  if (normalizedText.includes(normalizedQuery)) score += 1.05;
  if (compactText.includes(compactQuery)) score += 1;

  const queryTokens = tokenizeSearchText(query);
  if (queryTokens.length) {
    const matchedTokens = queryTokens.filter((token) => compactText.includes(compactSearchText(token)));
    score += (matchedTokens.length / queryTokens.length) * 0.75;
  }

  if (!approximate) return Math.min(score, 2.2);

  if (compactQuery.length >= 3 && compactText.length <= 700 && isSubsequence(compactQuery, compactText)) score += 0.35;
  if (hasApproximateSubstring(compactQuery, compactText)) score += 0.8;

  if (compactQuery.length >= 2 && compactText.length <= 700) {
    const textTokens = tokenizeSearchText(text);
    const maxDistance = compactQuery.length <= 4 ? 1 : compactQuery.length <= 8 ? 2 : 3;
    const hasCjkQuery = /[\u4e00-\u9fa5]/.test(compactQuery);
    const distinctiveChars = hasCjkQuery ? getDistinctiveSearchChars(compactQuery) : [];
    const minDistinctiveOverlap = Math.max(1, distinctiveChars.length - maxDistance);
    const closeMatch = textTokens.some((token) => {
      const compactToken = compactSearchText(token);
      if (Math.abs(compactToken.length - compactQuery.length) > maxDistance) return false;
      if (hasCjkQuery && distinctiveChars.length && getCharOverlap(distinctiveChars, compactToken) < minDistinctiveOverlap) return false;
      return levenshteinDistance(compactQuery, compactToken, maxDistance) <= maxDistance;
    });
    if (closeMatch) score += 0.65;
  }

  return Math.min(score, 2.2);
}

function getStorySearchMatch(story, keyword) {
  const normalizedKeyword = normalizeSearchText(keyword);
  if (!normalizedKeyword) return { matches: true, score: 0, fuzzy: false };
  const cacheKey = `${story.id}:${normalizedKeyword}`;
  if (searchMatchCache.has(cacheKey)) return searchMatchCache.get(cacheKey);
  const keywordVariants = getSearchVariants(normalizedKeyword);

  const fieldScores = getSearchFields(story).map((field) => {
    const normalizedField = normalizeSearchText(field.text);
    const compactField = compactSearchText(field.text);
    const compactKeyword = compactSearchText(normalizedKeyword);
    const exact = normalizedField.includes(normalizedKeyword) || compactField.includes(compactKeyword);
    const fuzzyScore = Math.max(...keywordVariants.map((variant) => getFuzzyTextScore(variant, field.text, { approximate: field.approximate })));
    return {
      name: field.name,
      score: fuzzyScore * field.weight,
      exact,
      fuzzy: fuzzyScore > 0 && !exact
    };
  });

  const best = fieldScores.reduce((currentBest, item) => (item.score > currentBest.score ? item : currentBest), { score: 0, fuzzy: false });
  const keywordTokens = uniqueItems(keywordVariants.flatMap((variant) => tokenizeSearchText(variant)));
  const storySearchText = compactSearchText(getStorySearchText(story));
  const tokenCoverage = keywordTokens.length
    ? keywordTokens.filter((token) => storySearchText.includes(compactSearchText(token))).length / keywordTokens.length
    : 0;
  const hasExactField = fieldScores.some((item) => item.exact);
  const compactKeyword = compactSearchText(normalizedKeyword);
  const fuzzyThreshold = compactKeyword.length <= 3 ? 4.2 : 3.2;
  const titleCoverage = getBestVariantCoverage(keywordVariants, story.title);
  const summaryCoverage = getBestVariantCoverage(keywordVariants, story.summary);
  const score = best.score + tokenCoverage * 4 + titleCoverage * 6 + summaryCoverage * 2 + Math.min(getStoryWeight(story), 12) / 4;

  const result = {
    matches: hasExactField || best.score >= fuzzyThreshold || tokenCoverage >= 0.75,
    score,
    fuzzy: !hasExactField && (best.fuzzy || (best.score > 0 && tokenCoverage < 1)),
    field: best.name
  };
  searchMatchCache.set(cacheKey, result);
  return result;
}

function slugifyHeading(text, index) {
  return `section-${index + 1}-${text.replace(/[^\u4e00-\u9fa5a-zA-Z0-9]+/g, '-').replace(/^-+|-+$/g, '').toLowerCase() || 'note'}`;
}

function getStorySections(story) {
  const sectionSize = story.guide ? 2 : 3;
  const sections = [];
  for (let index = 0; index < story.content.length; index += sectionSize) {
    const paragraphs = story.content.slice(index, index + sectionSize);
    const title = paragraphs[0].split(/[：:。]/)[0].slice(0, 18) || `第 ${sections.length + 1} 节`;
    sections.push({
      id: slugifyHeading(title, sections.length),
      title,
      paragraphs
    });
  }
  return sections;
}


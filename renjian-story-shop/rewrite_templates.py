    updated_count = 0
    for s in data:
        sid = s['id']
        if sid in rewrites:
            content = s.get('content', [])
            if len(content) >= 5:
                content[3] = rewrites[sid][0]
                content[4] = rewrites[sid][1]
                s['content'] = content
                updated_count += 1

    with open(STORIES_PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Updated {updated_count} stories in stories.json")

    # Update app.js
    with open(APP_JS_PATH, 'r', encoding='utf-8') as f:
        app = f.read()

    import re
    for sid, (new_p4, new_p5) in rewrites.items():
        # Find story in app.js
        pattern = f'"id": {sid},'
        idx = app.find(pattern)
        if idx == -1:
            print(f"  WARNING: Story {sid} not found in app.js")
            continue

        # Find the content array for this story
        content_start = app.find('"content": [', idx)
        if content_start == -1:
            print(f"  WARNING: Content array not found for story {sid}")
            continue

        # Find each content paragraph
        # We need to find and replace the 4th and 5th paragraphs
        # Parse the content array to find paragraph boundaries
        bracket_depth = 0
        in_string = False
        escape_next = False
        paragraphs = []
        para_start = None

        i = content_start + len('"content": [')
        while i < len(app):
            c = app[i]
            if escape_next:
                escape_next = False
                i += 1
                continue
            if c == '\\':
                escape_next = True
                i += 1
                continue
            if c == '"' and not in_string:
                in_string = True
                para_start = i
                i += 1
                continue
            if c == '"' and in_string:
                in_string = False
                paragraphs.append((para_start, i + 1))
                i += 1
                continue
            if c == ']' and not in_string:
                break
            i += 1

        if len(paragraphs) >= 5:
            # Replace 4th paragraph (index 3)
            p4_start, p4_end = paragraphs[3]
            p5_start, p5_end = paragraphs[4]

            # Need to handle the comma between paragraphs
            # The 4th paragraph is followed by a comma, then the 5th
            old_p4 = app[p4_start:p4_end]
            old_p5 = app[p5_start:p5_end]

            app = app[:p4_start] + json.dumps(new_p4, ensure_ascii=False) + app[p4_end:p5_start] + json.dumps(new_p5, ensure_ascii=False) + app[p5_end:]

    with open(APP_JS_PATH, 'w', encoding='utf-8') as f:
        f.write(app)


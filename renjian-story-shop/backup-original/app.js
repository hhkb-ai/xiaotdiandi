function sortStories(storiesToSort) {
  const list = [...storiesToSort];
  if (state.sort === 'latest') return list.sort((a, b) => b.id - a.id);
  if (state.sort === 'quality') return list.sort((a, b) => getStoryWeight(b) - getStoryWeight(a) || b.id - a.id);

  const keyword = state.keyword.trim().toLowerCase();
  return list.sort((a, b) => {
    if (!keyword) return b.id - a.id;
    return getSearchScore(b, keyword) - getSearchScore(a, keyword) || b.id - a.id;
  });
}


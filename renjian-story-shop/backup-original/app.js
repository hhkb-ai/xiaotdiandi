  if (story.guide) score += 8;
  if (story.category === '实用知识') score += 7;
  if (story.category === '求职复盘') score += 7;
  if (story.category === '学习成长') score += 5;
  if (story.category === '安全与情绪') score += 4;
  if (story.category === '活动与关系') score += 2;
  if (title.includes('知识') || title.includes('笔记') || title.includes('复习') || title.includes('时间管理')) score += 4;
  if (title.includes('四六级') || title.includes('四级') || title.includes('六级') || title.includes('优惠') || title.includes('折扣') || title.includes('省钱')) score += 5;
  if (title.includes('学生票') || title.includes('教育优惠') || title.includes('软件') || title.includes('电脑') || title.includes('教材')) score += 4;
  if (title.includes('求职') || title.includes('实习') || title.includes('Offer') || title.includes('大厂') || title.includes('工作')) score += 5;

function getRelatedStories(story, limit = 3) {
  return stories
    .filter((item) => item.id !== story.id)
    .map((item) => {
      let score = 0;
      if (item.category === story.category) score += 6;
      if (categoryGroups['学习知识'].includes(item.category) && categoryGroups['学习知识'].includes(story.category)) score += 2;
      const storyTags = new Set(getStoryTags(story));
      getStoryTags(item).forEach((tag) => {
        if (storyTags.has(tag)) score += 2;
      });
      score += Math.min(getStoryWeight(item), 10) / 5;
      return { item, score };
    })
    .filter(({ score }) => score > 0)
    .sort((a, b) => b.score - a.score || b.item.id - a.item.id)
    .slice(0, limit)
    .map(({ item }) => item);
}

